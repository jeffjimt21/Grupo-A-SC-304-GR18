private void mostrarSoloGanador(tropas.Tropa tJugador, tropas.Tropa tCPU) {
    if (tJugador == null && tCPU == null){
        return;
    }
    
    tropas.Tropa ganador = null;
    boolean esJugador = false;
    
    if (tJugador != null && tCPU == null){
        ganador = tJugador;
        esJugador = true;
    } else if (tJugador == null && tCPU != null){
        ganador =tCPU;
        esJugador = false;
    }else if (tJugador != null && tCPU != null){
        if (tJugador.getDanio() > tCPU.getDanio()) {
            ganador = tJugador;
            esJugador = true;
        }else if (tCPU.getDanio() > tJugador.getDanio()) {
            ganador = tCPU;
            esJugador = false;
        }else {
            limpiarCamino();
            return;
          }  
    }
    
    if (ganador == null){
        return;
    }
    
    limpiarCamino();
    mostrarTropaEnCamino(camino1Pos2, esJugador, 1);
    actualizarContadoresDeCola();
    
    javax.swing.Timer timer = new javax.swing.Timer(2000, new java.awt.event.ActionListener() {
        @Override
        public void actionPerformed(ActionEvent e) {
            limpiarCamino();
        }
    });
    timer.setRepeats(false);
    timer.start();
    
}
private void mostrarGanadorPorCamino(Tropa j, Tropa c, int camino) {
    if (j == null && c == null) {
        return;
    }

    Tropa ganador = null;
    boolean esJugador = false;

    if (j != null && c == null) {
        ganador = j;
        esJugador = true;
    } else if (j == null && c != null) {
        ganador = c;
        esJugador = false;
    } else {
        // Hay tropa de los dos lados
        if (j.getFortaleza().equals(c.getTipo())) {
            ganador = j;
            esJugador = true;
        } else if (c.getFortaleza().equals(j.getTipo())) {
            ganador = c;
            esJugador = false;
        } else {
            // empate: no se muestra nadie
            return;
        }
    }

    javax.swing.JPanel panel;

    if (camino == 1) {
        panel = esJugador ? camino1Pos1 : camino2Pos1;
    } else {
        panel = esJugador ? camino1Pos2 : camino2Pos2;
    }

    // Mostrar solo al ganador
    mostrarTropaEnCamino(panel, esJugador, camino);

    // Quitar ganador después de 2 segundos
    javax.swing.Timer t = new javax.swing.Timer(2000, new java.awt.event.ActionListener() {
        @Override
        public void actionPerformed(java.awt.event.ActionEvent e) {
            limpiarCamino();
        }
    });
    t.setRepeats(false);
    t.start();
}
