private String obtenerImagenCombinada(Tropa t1, Tropa t2) {
    if (t1 == null || t2 == null) return null;

    String tipo1 = t1.getClass().getSimpleName();
    String tipo2 = t2.getClass().getSimpleName();

    // Ordenar alfabéticamente para evitar duplicados
    String a = tipo1.compareTo(tipo2) <= 0 ? tipo1 : tipo2;
    String b = tipo1.compareTo(tipo2) <= 0 ? tipo2 : tipo1;

    if (a.equals("Arquero") && b.equals("Caballero")) return "/imagenes/arquero_caballero.png";
    if (a.equals("Caballero") && b.equals("Mago")) return "/imagenes/caballero_mago.png";
    if (a.equals("Arquero") && b.equals("Mago")) return "/imagenes/mago_arquero.png";
    if (!tipo1.equals(tipo2)) return "/imagenes/todos.png";
    return null;
}
private Tropa obtenerSegundaTropa(int camino, boolean esJugador) {
    Cola original = esJugador
        ? (camino == 1 ? invasion.obtenerBatallaActual().camino1Jugador : invasion.obtenerBatallaActual().camino2Jugador)
        : (camino == 1 ? invasion.obtenerBatallaActual().camino1CPU : invasion.obtenerBatallaActual().camino2CPU);

    if (original == null) return null;

    Cola temp = new Cola();
    Tropa segunda = null;
    int contador = 0;

    while (!original.estaVacia()) {
        try {
            Object obj = original.desencolar();
            temp.encolar((Tropa) obj); 
            contador++;
            if (contador == 2) {
                segunda = (Tropa) obj;
                break;
            }
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    // Restaurar cola
    while (!temp.estaVacia()) {
        try {
            original.encolar(temp.desencolar());
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    return segunda;
}
private String obtenerImagenSegunCola(int camino, boolean esJugador) {
    Batalla batalla = invasion.obtenerBatallaActual();
    Cola cola = esJugador ? batalla.getCaminoJugador(camino) : batalla.getCaminoCPU(camino);

    if (cola == null || cola.estaVacia()) return null;

    // Contadores por tipo
    int caballeros = 0, arqueros = 0, magos = 0;

    Cola temp = new Cola();
    while (!cola.estaVacia()) {
        try {
            Tropa t = (Tropa) cola.desencolar();
            temp.encolar(t);
            
            if (t instanceof Caballero) caballeros++;
            else if (t instanceof Arquero) arqueros++;
            else if (t instanceof Mago) magos++;
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    while (!temp.estaVacia()) {
        try {
            cola.encolar(temp.desencolar());
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    // Decidir imagen
    int tipos = (caballeros > 0 ? 1 : 0) + (arqueros > 0 ? 1 : 0) + (magos > 0 ? 1 : 0);

    if (tipos == 1) {
        if (caballeros > 0) return "/imagenes/caballero.png";
        if (arqueros > 0) return "/imagenes/arquero.png";
        if (magos > 0) return "/imagenes/mago.png";
    } else if (tipos == 2) {
        if (caballeros > 0 && arqueros > 0) return "/imagenes/arquero_caballero.png";
        if (caballeros > 0 && magos > 0) return "/imagenes/caballero_mago.png";
        if (arqueros > 0 && magos > 0) return "/imagenes/mago_arquero.png";
    } else if (tipos == 3) {
        return "/imagenes/todos.png";
    }

    return null;
}
private int obtenerRepeticionesDominantes(int camino, boolean esJugador) {
    Batalla batalla = invasion.obtenerBatallaActual();
    Cola cola = esJugador ? batalla.getCaminoJugador(camino) : batalla.getCaminoCPU(camino);

    if (cola == null || cola.estaVacia()) return 0;

    int caballeros = 0, arqueros = 0, magos = 0;

    Cola temp = new Cola();
    while (!cola.estaVacia()) {
        try {
            Tropa t = (Tropa) cola.desencolar();
            temp.encolar(t);
            
            if (t instanceof Caballero) caballeros++;
            else if (t instanceof Arquero) arqueros++;
            else if (t instanceof Mago) magos++;
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    while (!temp.estaVacia()) {
        try {
            cola.encolar(temp.desencolar());
        } catch (Exception ex) {
            Logger.getLogger(FrmBatalla.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    int tipos = (caballeros > 0 ? 1 : 0) + (arqueros > 0 ? 1 : 0) + (magos > 0 ? 1 : 0);

    if (tipos == 1) {
        return Math.max(caballeros, Math.max(arqueros, magos));
    } else if (tipos == 2) {
        // Si hay dos tipos, y ambos tienen más de 1, mostrar el mínimo
        int[] repeticiones = {caballeros, arqueros, magos};
        int min = Integer.MAX_VALUE;
        for (int r : repeticiones) {
            if (r > 0) min = Math.min(min, r);
        }
        return min > 1 ? min : 0;
    }

    // Si hay 3 tipos distintos, no mostrar badge
    return 0;
}

