    private void btnAgregarTropaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTropaActionPerformed
        // TODO add your handling code here:
        
        int limite=batalla.getRonda()+ 1;
        int contador=0;
        
        if (tropasAgregadas >= limite) {
        lblTropasAgregadas.setText("Llegaste al limite de esta ronda");
        return;
        }

        
            //Toma de datos
            String tipo = (String) cmbTiposTropas.getSelectedItem();
            String caminos= (String) jComboBox2.getSelectedItem();   
            
        
            int camino = 0;
            //Escoger Camino
             if (caminos.equals("Camino 1")) {
                 camino = 1;
             } else{
                 camino =2;
                 }
             
             //Tipo y creacion de la tropa
            Tropa tropa = new Tropa();
             
            if (tipo.equals("Arquero")) {
                
                tropa = new Arquero();
                
            } else if(tipo.equals("Caballero")){
                
                tropa = new Caballero();
            
            } else if(tipo.equals("Mago")){
            
                tropa = new Mago();
            
            } else {
            
                tipo="Arquero";
                tropa = new Arquero();
            
            }
            
            batalla.prepararJugador(camino, tropa);
            tropasAgregadas++;
            lblTropasAgregadas.setText("Tropas agregadas: " + tropasAgregadas + "/" + limite);

            
           if (tropasAgregadas == limite) {
        lblTropasAgregadas.setText("Llegaste al limite de esta ronda");
        btnAgregarTropa.setEnabled(false);
    }
           
            int limitecpu =batalla.getRonda();
           
           if (tropasAgregadasCpu >= limitecpu) {
        lblTropasAgregadasCPU.setText("Tropas agregadas CPU: " + tropasAgregadasCpu + "/" + limitecpu);
            
        return;
        }
           
          
             
            batalla.prepararCPU();
            
           tropasAgregadasCpu++;
           
           if (tropasAgregadasCpu == limitecpu) {
       lblTropasAgregadasCPU.setText("Tropas agregadas CPU: " + tropasAgregadasCpu + "/" + limitecpu);
    }
           
           
        
    }//GEN-LAST:event_btnAgregarTropaActionPerformed

