    private void btnEmpezarBatallaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEmpezarBatallaActionPerformed
        // TODO add your handling code here:
        
                                                       
    try {
        if (!batalla.batallaTerminada()) {
            batalla.Enfrentamiento();
            lblVidaJugador.setText("Vida Jugador: " + jugador.getCastillo().getVida());
            lblVidaCPU.setText("Vida CPU: " + cpu.getCastillo().getVida());

            if (batalla.rondaTerminada()) {//todo esta vacio
               
                lblResultadoBatalla.setText("Ronda: " + batalla.getRonda() + " terminada.");
                batalla.AumentarRonda();
                tropasAgregadas = 0;//devolver parametro reiniciado
                btnAgregarTropa.setEnabled(true);//permite boton para agregar tropa
                lblTropasAgregadas.setText("Nueva ronda: " + " , maximo: "+batalla.getRonda()+" : " + 1);
                
            }

        } else {
            lblResultadoBatalla.setText("Resultado batalla: " + batalla.resultadoBatalla());
            btnEmpezarBatalla.setEnabled(false);
        }
    } catch (Exception e) {
        
    }


        
    }//GEN-LAST:event_btnEmpezarBatallaActionPerformed

